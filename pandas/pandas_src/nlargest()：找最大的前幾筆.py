# 實付金額最高的 3 筆訂單是哪幾筆？
import pandas as pd


### 建立訂單資料
data = {
    "訂單編號": ["A001", "A002", "A003", "A004", "A005", "A006"],
    "餐點金額": [180, 320, 250, 450, 150, 380],
    "外送費": [30, 0, 40, 0, 30, 20],
    "折扣": [20, 50, 0, 80, 10, 30],
    "狀態": ["已完成", "已完成", "已取消", "已完成", "已取消", "已完成"]
}

df = pd.DataFrame(data)


### 計算實付金額
df["實付金額"] = (df["餐點金額"] + df["外送費"] - df["折扣"] )

### 找出實付金額最高的 3 筆
top3 = df.nlargest(
    3,
    "實付金額"
)

print(top3)
